from sklearn.metrics import accuracy_score, recall_score, f1_score, precision_score

n_estimators_list = [100, 200, 300, 400]
max_depth_list = [5, 10, 15, 20]

results = []

for n_estimators in n_estimators_list:
    for max_depth in max_depth_list:
        rf_model = RandomForestClassifier(n_estimators=n_estimators, max_depth=max_depth, random_state=42, class_weight='balanced')
        rf_model.fit(X_train, Y_train)
        y_pred = rf_model.predict(X_test)
        accuracy = accuracy_score(Y_test, y_pred)
        recall = recall_score(Y_test, y_pred)
        precision = precision_score(Y_test, y_pred)
        f1 = f1_score(Y_test, y_pred)
        results.append({'n_estimators': n_estimators, 'max_depth': max_depth, 'accuracy': accuracy, 'recall': recall, 'precision': precision, 'f1': f1})

results_df = pd.DataFrame(results)

results_df = results_df.sort_values(by=['accuracy', 'recall', 'precision', 'f1'], ascending=False)

